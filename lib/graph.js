'use strict';

// Repository graph (optional). Graphify (https://github.com/Graphify-Labs/graphify)
// turns a repository into graph.json: nodes with source locations, edges tagged
// EXTRACTED (read from the source) or INFERRED (resolved by graphify). The loop
// uses it as a structural index instead of opening files one by one.
//
// It is an external Python tool, never a dependency: when the binary is missing
// the command reports SKIPPED with the install command and the loop falls back
// to `lib/smart-context.js`. Query results are cached in graph.json, and an edge
// is evidence only when it is EXTRACTED — INFERRED edges are hypotheses.

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const GRAPH_DIR = 'graphify-out';
const GRAPH_FILE = 'graph.json';
const REPORT_FILE = 'GRAPH_REPORT.md';
const OUT_DIR = path.join('.ai-engineering-loop', 'graph');
const MAX_GRAPH_BYTES = 64 * 1024 * 1024;
const MAX_RESULTS = 20;
const INSTALL_HINT = 'uv tool install graphifyy (or: pipx install graphifyy), then `graphify install`';
const EVIDENCE_CONFIDENCE = new Set(['EXTRACTED']);

function graphError(message, code = 'GRAPH_FAILED', { why = null, fix = null } = {}) {
  const error = new Error(message);
  error.code = code;
  error.why = why;
  error.fix = fix;
  return error;
}

function onPath(command, env = process.env) {
  const directories = String(env.PATH || env.Path || '').split(path.delimiter).filter(Boolean);
  const extensions = process.platform === 'win32' ? ['', '.exe', '.cmd', '.bat'] : [''];
  for (const directory of directories) {
    for (const extension of extensions) {
      try {
        const stat = fs.statSync(path.join(directory, `${command}${extension}`));
        if (stat.isFile()) return path.join(directory, `${command}${extension}`);
      } catch {
        continue;
      }
    }
  }
  return null;
}

// Detection only stats the binary; nothing is executed until `build` is asked to.
function detect(env = process.env) {
  const binary = onPath('graphify', env);
  return { available: Boolean(binary), binary, install: INSTALL_HINT };
}

function graphPath(rootDir) {
  return path.join(rootDir, OUT_DIR, GRAPH_FILE);
}

function reportPath(rootDir) {
  return path.join(rootDir, OUT_DIR, REPORT_FILE);
}

function readGraph(rootDir) {
  const filePath = graphPath(rootDir);
  let stat;
  try {
    stat = fs.lstatSync(filePath);
  } catch {
    return null;
  }
  if (stat.isSymbolicLink() || !stat.isFile() || stat.size > MAX_GRAPH_BYTES) {
    throw graphError(`${OUT_DIR}/${GRAPH_FILE} is not a readable regular file.`, 'INVALID_GRAPH', {
      why: 'The cached graph is the only input to `graph query`; a symlink or oversized file is not trusted.',
      fix: `Delete ${OUT_DIR} and run \`ael graph build\` again.`
    });
  }
  let graph;
  try {
    graph = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  } catch (cause) {
    throw graphError(`${OUT_DIR}/${GRAPH_FILE} is not valid JSON: ${cause.message}`, 'INVALID_GRAPH', {
      why: 'A half-written graph would silently answer with partial edges.',
      fix: 'Run `ael graph build` again; it rebuilds the file from scratch.'
    });
  }
  // graphify writes networkx node-link output: `links`, not `edges`.
  if (graph && !Array.isArray(graph.edges) && Array.isArray(graph.links)) graph.edges = graph.links;
  if (!graph || !Array.isArray(graph.nodes)) {
    throw graphError(`${OUT_DIR}/${GRAPH_FILE} has no nodes array.`, 'INVALID_GRAPH', {
      why: 'Only graphify networkx node-link output is readable here.',
      fix: 'Run `ael graph build` again so the file is regenerated by graphify.'
    });
  }
  return { graph, file: `${OUT_DIR}/${GRAPH_FILE}`.split(path.sep).join('/'), bytes: stat.size };
}

function build(rootDir, { run = true, env = process.env } = {}) {
  const found = detect(env);
  if (!found.available) {
    return { status: 'SKIPPED', reason: 'graphify-not-installed', install: INSTALL_HINT, fallback: 'smart-context' };
  }
  const target = path.join(rootDir, OUT_DIR);
  const output = path.join(rootDir, GRAPH_DIR);
  if (!run) return { status: 'PLANNED', binary: found.binary, command: ['graphify', '.'], output: GRAPH_DIR, target: OUT_DIR };
  fs.mkdirSync(target, { recursive: true });
  const result = spawnSync(found.binary, ['.'], {
    cwd: rootDir,
    encoding: 'utf8',
    env: { ...env, GRAPHIFY_OUT: output },
    timeout: 30 * 60 * 1000
  });
  if (result.error) {
    return { status: 'SKIPPED', reason: 'graphify-failed', detail: result.error.message, install: INSTALL_HINT, fallback: 'smart-context' };
  }
  const produced = path.join(output, GRAPH_FILE);
  if (!fs.existsSync(produced)) {
    return {
      status: 'SKIPPED',
      reason: 'no-graph-output',
      exitCode: result.status,
      detail: String(result.stderr || result.stdout || '').split('\n').filter(Boolean).slice(-3).join(' | '),
      install: INSTALL_HINT,
      fallback: 'smart-context'
    };
  }
  const copied = path.join(target, GRAPH_FILE);
  fs.copyFileSync(produced, copied);
  if (fs.existsSync(path.join(output, REPORT_FILE))) {
    fs.copyFileSync(path.join(output, REPORT_FILE), path.join(target, REPORT_FILE));
  }
  const cached = readGraph(rootDir);
  return {
    status: 'BUILT',
    file: cached.file,
    nodes: cached.graph.nodes.length,
    edges: Array.isArray(cached.graph.edges) ? cached.graph.edges.length : 0,
    bytes: cached.bytes
  };
}

function confidenceOf(edge) {
  return String(edge?.confidence || edge?.confidence_tag || 'UNKNOWN').toUpperCase();
}

// Every match carries the file it came from and whether the edge that led here
// is EXTRACTED. A query result is a pointer to read, never a quote of code.
function query(rootDir, text, { limit = MAX_RESULTS, kind = null } = {}) {
  const cached = readGraph(rootDir);
  if (!cached) {
    throw graphError('No repository graph yet.', 'GRAPH_MISSING', {
      why: '`graph query` reads the cached graph instead of opening files; without it there is nothing to query.',
      fix: 'Run `ael graph build` (needs graphify: ' + INSTALL_HINT + '). Without graphify, use `ael context query "<text>"`.'
    });
  }
  const needle = String(text || '').trim().toLowerCase();
  if (!needle) throw graphError('Provide a query text.', 'GRAPH_QUERY_EMPTY', { why: 'An empty query would return the whole graph.', fix: 'Pass a symbol, file, or question fragment.' });
  const byId = new Map(cached.graph.nodes.map((node) => [node.id, node]));
  const nodes = cached.graph.nodes
    .filter((node) => !kind || node.file_type === kind)
    .filter((node) => `${node.id} ${node.label || ''} ${node.source_file || ''}`.toLowerCase().includes(needle))
    .slice(0, limit)
    .map((node) => ({
      id: node.id,
      label: node.label || null,
      file: node.source_file || null,
      fileType: node.file_type || null,
      community: node.community ?? null
    }));
  const edges = (cached.graph.edges || [])
    .filter((edge) => {
      const source = byId.get(edge.source);
      const target = byId.get(edge.target);
      return `${edge.source} ${edge.target} ${source?.label || ''} ${target?.label || ''}`.toLowerCase().includes(needle);
    })
    .slice(0, limit)
    .map((edge) => {
      const confidence = confidenceOf(edge);
      return {
        from: byId.get(edge.source)?.label || edge.source,
        to: byId.get(edge.target)?.label || edge.target,
        relation: edge.relation || null,
        confidence,
        evidence: EVIDENCE_CONFIDENCE.has(confidence),
        file: edge.source_file || null
      };
    });
  return { query: String(text), file: cached.file, nodes, edges, truncated: nodes.length === limit || edges.length === limit };
}

function status(rootDir) {
  const found = detect();
  let cached = null;
  try {
    const read = readGraph(rootDir);
    if (read) cached = { file: read.file, bytes: read.bytes, nodes: read.graph.nodes.length, edges: (read.graph.edges || []).length };
  } catch (err) {
    cached = { error: err.message, code: err.code };
  }
  return { graphify: found.available, binary: found.binary, install: INSTALL_HINT, graph: cached };
}

module.exports = {
  GRAPH_DIR,
  GRAPH_FILE,
  OUT_DIR,
  INSTALL_HINT,
  detect,
  build,
  query,
  status,
  readGraph,
  confidenceOf,
  graphPath
};
